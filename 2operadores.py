# Os operadores aritméticos em Python são usados para realizar cálculos matemáticos

#Soma
a = 10
b = 5
resultado = a + b
print("Soma:", resultado)  # Saída: 15

#Subtração
a = 10
b = 5
resultado = a - b
print("Subtração:", resultado)  # Saída: 5

#Multiplicação
a = 10
b = 5
resultado = a * b
print("Multiplicação:", resultado)  # Saída: 50

#Divisão
a = 10
b = 4
resultado = a / b
print("Divisão:", resultado)  # Saída: 2.5

#Exponeciação
base = 2
expoente = 3
resultado = base ** expoente
print("Exponenciação:", resultado)  # Saída: 8

#Resto da divisão
a = 10
b = 4
resultado = a % b
print("Resto da Divisão (Módulo):", resultado)  # Saída: 2

#Negação: inverte o sinal de um número
a = 10
resultado = -a
print("Negativo:", resultado)  # Saída: -10

# ordem de precedência matemática (parênteses > exponenciação > multiplicação/divisão/módulo > soma/subtração).
