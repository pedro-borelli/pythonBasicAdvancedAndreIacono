# Os operadores de comparação em Python são usados para comparar valores.
# Eles sempre retornam um valor booleano (True ou False), dependendo do resultado da comparação.

# Igualdade (==) Verifica se dois valores são iguais.
a = 10
b = 10
print(a == b)  # True
print(a == 5)  # False

# Diferença (!=) Verifica se dois valores são diferentes.
a = 10
b = 5
print(a != b)  # True
print(a != 10) # False

# Maior que (>) Verifica se o valor da esquerda é maior que o da direita.
a = 10
b = 5
print(a > b)  # True
print(a > 20) # False

# Menor que (<) Verifica se o valor da esquerda é menor que o da direita.
a = 5
b = 10
print(a < b)  # True
print(a < 2)  # False

# Maior ou Igual (>=) Verifica se o valor da esquerda é maior ou igual ao da direita.
a = 10
b = 10
print(a >= b)  # True
print(a >= 20) # False

# Menor ou Igual (<=) Verifica se o valor da esquerda é menor ou igual ao da direita.
a = 5
b = 10
print(a <= b)  # True
print(a <= 2)  # False
